#!/usr/bin/env python3
"""Fold the whole tool into one file that still runs.

The obvious way to make a single file is to paste fifty modules together and
fix the imports by hand. That produces something nobody can maintain and that
silently diverges from the real thing the first time either changes.

This does it the other way round. The package is zipped, the zip is embedded
as base64 in a generated script, and at run time the script hands that archive
to `zipimport`, which Python has always been able to import from. Nothing is
rewritten, so the code that runs from one file is byte for byte the code that
runs from fifty. The audit still cannot delete, the delete path still demands
its approval, and every guard is the same object it was.

    python3 experiment/build_single_file.py
    python3 experiment/genchain-all-in-one.py audit --help

It is a curiosity rather than the supported way to install this. The supported
way is to copy `generation_chain/` into a directory, which is already one
step.
"""
import base64
import io
import pathlib
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "experiment" / "genchain-all-in-one.py"

# The package, plus the top-level tools that ship beside it.
TREES = ["generation_chain"]
FILES = [
    "reclaim_test_protocol.py",   # the audit-and-reclaim loop
    "snapshot_churn_rig.py",      # the load generator
    "verify_restorable.py",       # the restore checker
    "snapshot_sizes.py",          # repository sizing and mount classification
    "package.py",                 # the release builder, folded into its own output
]
# Not python, so it cannot be a subcommand. It is carried anyway and written
# out by `cycle`, because a loop runner nobody can extract is a loop runner
# nobody runs.
EXTRAS = ["scripts/run-test-cycle.sh", "scripts/test-cycle.conf.example"]

TEMPLATE = '''#!/usr/bin/env python3
"""The whole Elasticsearch OCI reclamation tool, in one file.

Generated by experiment/build_single_file.py. Do not edit: edit the real
modules and rebuild, or the two will disagree and only one of them is tested.

The package below is a base64 zip, imported at run time with zipimport rather
than pasted together, so this file runs exactly the code the repository holds.

    python3 {name} audit      --help    the read-only audit
    python3 {name} reclaim    --help    the delete path, which needs an approval
    python3 {name} harness    --help    the audit-and-reclaim loop
    python3 {name} rig        --help    the load generator
    python3 {name} restorable --help    the restore checker
    python3 {name} sizes      --help    repository sizing
    python3 {name} package    --help    build a release archive
    python3 {name} probe      --help    which delete checksum a store takes
    python3 {name} cycle      CONFIG    run the loop from a config file

Built from {count} files, {raw:,} bytes of source.
"""
import base64
import binascii
import io
import os
import sys
import tempfile
import zipimport

_ARCHIVE = "{payload}"


def _install():
    """Put the embedded package on the import path.

    zipimport needs a file on disk, so the archive is written to a temporary
    one. It is left in place for the life of the process because the import
    system reads from it lazily, and removed on exit.
    """
    raw = base64.b64decode(_ARCHIVE)
    handle, path = tempfile.mkstemp(prefix="genchain-", suffix=".zip")
    with os.fdopen(handle, "wb") as fh:
        fh.write(raw)
    sys.path.insert(0, path)
    return path


COMMANDS = {{
    "audit": ("generation_chain.cli", "main"),
    "reclaim": ("generation_chain.reclaim.cli", "main"),
    "harness": ("reclaim_test_protocol", "main"),
    "rig": ("snapshot_churn_rig", "main"),
    "restorable": ("verify_restorable", "main"),
    "sizes": ("snapshot_sizes", "main"),
    "package": ("package", "build"),
    "probe": ("probe_checksums", "main"),
    "cycle": ("cycle_runner", "main"),
}}


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if not argv or argv[0] in ("-h", "--help"):
        sys.stderr.write(__doc__ + "\\n")
        return 0 if argv else 2
    name = argv[0]
    if name not in COMMANDS:
        sys.stderr.write(
            "no such command: {{}}\\nthere are: {{}}\\n".format(
                name, ", ".join(sorted(COMMANDS))))
        return 2
    path = _install()
    try:
        module_name, entry = COMMANDS[name]
        module = __import__(module_name, fromlist=["*"])
        sys.argv = [f"{{sys.argv[0]}} {{name}}"] + argv[1:]
        result = getattr(module, entry)()
        return 0 if result is None else result
    finally:
        try:
            os.unlink(path)
        except OSError:
            pass


if __name__ == "__main__":
    raise SystemExit(main())
'''


def collect():
    members, raw = [], 0
    for tree in TREES:
        for path in sorted((ROOT / tree).rglob("*.py")):
            members.append((str(path.relative_to(ROOT)), path.read_bytes()))
    for name in FILES + EXTRAS:
        path = ROOT / name
        if path.exists():
            members.append((name, path.read_bytes()))
    for extra, name in (("_probe_checksums.py", "probe_checksums.py"),
                        ("_cycle.py", "cycle_runner.py")):
        path = ROOT / "experiment" / extra
        if path.exists():
            members.append((name, path.read_bytes()))
    raw = sum(len(b) for _, b in members)
    return members, raw


def build():
    members, raw = collect()
    buffer = io.BytesIO()
    # Deterministic: fixed timestamps, sorted members, so the same tree
    # produces the same file and a diff means something changed.
    with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
        for name, body in members:
            info = zipfile.ZipInfo(name, date_time=(1980, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            archive.writestr(info, body)
    payload = base64.b64encode(buffer.getvalue()).decode("ascii")
    OUT.write_text(TEMPLATE.format(
        name=OUT.name, payload=payload, count=len(members), raw=raw))
    OUT.chmod(0o755)
    print(f"  {OUT.relative_to(ROOT)}")
    print(f"  folded {len(members)} files, {raw:,} bytes of source")
    print(f"  into {OUT.stat().st_size:,} bytes, one file")


if __name__ == "__main__":
    build()
